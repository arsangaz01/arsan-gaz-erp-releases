namespace ArsanGazERP.Data;

// PostgreSQL DDL for the tables that are not part of an EF model (they are created by raw SQL on SQLite too).
// Column types mirror the SQLite storage on purpose: the timestamps of these tables are ISO-8601 text written and
// compared by CampaignStore, so they stay TEXT (the database uses the C collation, which orders them like SQLite).
public static class PostgresSchema
{
    // EF model tables added after the erp schema was first created (CreateTablesAsync runs only on an empty schema).
    // Names and types match what the EF model plus ArsanDbEf.ApplyPostgresConventions would create.
    public const string Erp = """
CREATE TABLE IF NOT EXISTS CylinderTrips (
 Id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_cylindertrips PRIMARY KEY,
 Title text NOT NULL,
 Status integer NOT NULL,
 StartedAt timestamp without time zone NOT NULL,
 ClosedAt timestamp without time zone NULL,
 Note text NULL,
 CreatedBy text NULL
);
CREATE INDEX IF NOT EXISTS ix_cylindertrips_status ON CylinderTrips(Status);
CREATE TABLE IF NOT EXISTS CylinderTripVehicles (
 Id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_cylindertripvehicles PRIMARY KEY,
 TripId integer NOT NULL CONSTRAINT fk_cylindertripvehicles_cylindertrips_tripid REFERENCES CylinderTrips(Id) ON DELETE CASCADE,
 Plate text NOT NULL,
 AddedAt timestamp without time zone NOT NULL,
 ReturnedAt timestamp without time zone NULL
);
CREATE INDEX IF NOT EXISTS ix_cylindertripvehicles_tripid_plate ON CylinderTripVehicles(TripId, Plate);
CREATE TABLE IF NOT EXISTS CylinderTripCylinders (
 Id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_cylindertripcylinders PRIMARY KEY,
 TripId integer NOT NULL CONSTRAINT fk_cylindertripcylinders_cylindertrips_tripid REFERENCES CylinderTrips(Id) ON DELETE CASCADE,
 CylinderId integer NOT NULL CONSTRAINT fk_cylindertripcylinders_cylinders_cylinderid REFERENCES Cylinders(Id) ON DELETE RESTRICT,
 VehiclePlate text NOT NULL,
 SerialNumber text NOT NULL,
 GasType text NOT NULL,
 LoadedAt timestamp without time zone NOT NULL,
 DeliveredAt timestamp without time zone NULL,
 ReturnedAt timestamp without time zone NULL
);
CREATE INDEX IF NOT EXISTS ix_cylindertripcylinders_tripid_cylinderid ON CylinderTripCylinders(TripId, CylinderId);
CREATE INDEX IF NOT EXISTS ix_cylindertripcylinders_cylinderid ON CylinderTripCylinders(CylinderId);
CREATE TABLE IF NOT EXISTS Vehicles (
 Id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_vehicles PRIMARY KEY,
 Plate text NOT NULL,
 Name text NULL,
 VehicleType text NULL,
 DriverName text NULL,
 CylinderCapacity integer NULL,
 Note text NULL,
 IsActive boolean NOT NULL DEFAULT TRUE,
 CreatedAt timestamp without time zone NOT NULL,
 UpdatedAt timestamp without time zone NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_vehicles_plate ON Vehicles(Plate);
INSERT INTO Vehicles (Plate, IsActive, CreatedAt)
SELECT DISTINCT p.Plate, TRUE, LOCALTIMESTAMP(0) FROM (
 SELECT TRIM(VehiclePlate) AS Plate FROM Cylinders WHERE VehiclePlate IS NOT NULL
 UNION SELECT TRIM(Plate) FROM CylinderTripVehicles
 UNION SELECT TRIM(VehiclePlate) FROM CylinderTripCylinders
) p WHERE p.Plate <> ''
ON CONFLICT (Plate) DO NOTHING;
DO $$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM CylinderTripCylinders GROUP BY TripId, CylinderId HAVING COUNT(*) > 1) THEN
  CREATE UNIQUE INDEX IF NOT EXISTS ux_cylindertripcylinders_tripid_cylinderid ON CylinderTripCylinders(TripId, CylinderId);
 END IF;
END $$;
""";

